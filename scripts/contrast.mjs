// Generates presets/PALETTES.md with WCAG contrast numbers computed from palettes.ts.
import fs from 'node:fs';
const src = fs.readFileSync(new URL('../presets/src/palettes.ts', import.meta.url), 'utf8');
const rows = src.split('\n').filter((l) => l.trim().startsWith("{ id: '")).map((l) => {
  const g = (k) => (l.match(new RegExp(k + ": '([^']+)'")) || [])[1];
  return ['', g('id'), g('name'), g('bg'), g('panel'), g('text'), g('muted'), g('accent'), g('hot'), '', g('note')];
});
const lum = (h) => { const c = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4)); return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]; };
const cr = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return ((x + 0.05) / (y + 0.05)).toFixed(2); };
let out = '# Palettes (generated by `npm run contrast` — do not edit by hand)\n\nContrast = WCAG 2.x ratio. AA body text needs 4.5, large text 3.0.\n\n| id | bg | panel | text | accent | hot | text/bg | text/panel | accent/bg | hot/bg | muted/panel | note |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n';
let fails = [];
for (const m of rows) {
  const [, id, , bg, panel, text, muted, accent, hot, , note] = m;
  const v = [cr(text, bg), cr(text, panel), cr(accent, bg), cr(hot, bg), cr(muted, panel)];
  if (+v[0] < 7 || +v[1] < 7 || +v[2] < 3 || +v[3] < 3) fails.push(`${id}: ${v.join(' ')}`);
  out += `| ${id} | \`${bg}\` | \`${panel}\` | \`${text}\` | \`${accent}\` | \`${hot}\` | ${v.join(' | ')} | ${note} |\n`;
}
out += '\nArea ratios per role are in `palettes.ts` (`ratio`): dark default bg 58 / panel 28 / text 8 / accent 4 / hot 2; light default 50 / 36 / 9 / 3.5 / 1.5. These are our defaults, not tested for performance.\n';
fs.writeFileSync(new URL('../presets/PALETTES.md', import.meta.url), out);
console.log(`${rows.length} palettes`); if (fails.length) console.log('BELOW TARGET:\n' + fails.join('\n'));
